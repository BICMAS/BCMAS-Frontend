def validate_adjustment(model: BaseModel, vctx: dict[str, Any]) -> list[ValidationIssue]:
    assert isinstance(model, PlanAdjustmentPayload)
    issues: list[ValidationIssue] = []
    goal_ids = set(vctx["goal_ids"])
    actions: dict[str, list[str]] = vctx["action_ids"]
    new_goals: dict[str, Any] | None = vctx.get("new_goals")
    if model.plan_id != vctx["plan_id"]:
        issues.append(
            ValidationIssue(code="fixed_field", path="plan_id", message="the plan cannot be changed")
        )
    for i, change in enumerate(model.changes):
        path = f"changes[{i}]"
        if change.op == "add_goal":
            if (
                change.goal is None
                or new_goals is None
                or change.goal.skill_id not in new_goals["goal_skills"]
            ):
                issues.append(
                    ValidationIssue(
                        code="unknown_id", path=path, message="new goals must target proposed skills"
                    )
                )
                continue
            allowed = new_goals["goal_skills"][change.goal.skill_id]["catalogue"]
            for action in change.goal.actions:
                if action.type == "learning" and action.catalogue_item_id not in allowed:
                    issues.append(
                        ValidationIssue(
                            code="unknown_id",
                            path=path,
                            message=f"'{action.catalogue_item_id}' is not an organisational resource",
                        )
                    )
        elif change.goal_ref not in goal_ids:
            issues.append(
                ValidationIssue(code="unknown_id", path=f"{path}.goal_ref", message="unknown plan goal")
            )
        elif change.op in ("remove_action", "update_action") and change.action_ref not in actions.get(
            change.goal_ref, []
        ):
            issues.append(
                ValidationIssue(code="unknown_id", path=f"{path}.action_ref", message="unknown plan action")
            )
        elif change.op == "add_action" and change.action is None:
            issues.append(
                ValidationIssue(code="missing", path=f"{path}.action", message="add_action needs an action")
            )
    return issues


def commit_adjustment(
    record: DraftRecord, model: BaseModel, principal: Principal, source: Literal["ai", "ai_edited"]
) -> list[CommitInstruction]:
    """BE-053 PATCH /development-plans/{plan_id}, executed by the frontend after approval."""
    assert isinstance(model, PlanAdjustmentPayload)
    body = {
        "changes": [c.model_dump(mode="json") for c in model.changes],
        "source": {
            "type": source,
            "draft_id": record.draft.draft_id,
            "model": record.draft.provenance.model,
            "prompt_version": record.draft.provenance.prompt_version,
        },
    }
    return [
        CommitInstruction(
            endpoint_id="BE-053",
            method="PATCH",
            path=f"/development-plans/{model.plan_id}",
            body=body,
            endpoint_status="unknown",
        )
    ]


HANDLER = KindHandler(
    kind="plan_adjustment",
    payload_model=PlanAdjustmentPayload,
    validate=validate_adjustment,
    commit=commit_adjustment,
)
