SPEC = replace(
    declared("dev_plan.review_plan"),
    implemented=True,
    optional_endpoints=("BE-022", "BE-040", "BE-041", "BE-042"),
)
DISCLAIMER = (
    "AI-proposed changes to an official development plan. Nothing changes until a reviewer approves "
    "them, and verified capability levels are never changed by the AI."
)
TRIGGERS: frozenset[str] = frozenset(
    {"manual", "capability_verified", "learning_completed", "coaching_evaluated", "assessment_reported"}
)


def _when(value: datetime | None) -> datetime | None:
    if value is None:
        return None
    return value if value.tzinfo else value.replace(tzinfo=UTC)


def compute_progress(
    plan: DevelopmentPlanDTO,
    context: CapabilityContext,
    *,
    now: datetime | None = None,
    extra_evidence: list[EvidenceItem] | None = None,
) -> PlanProgressReport:
    now = now or datetime.now(UTC)
    verified = {c.skill_id: c for c in context.capabilities or []}
    completed = {r.catalogue_item_id for r in context.learning_history or [] if r.status == "completed"}
    in_progress = {r.catalogue_item_id for r in context.learning_history or [] if r.status == "in_progress"}
    names = {sid: s.name for sid, s in context.skills.items()}
    created = _when(plan.created_at) or now
    goals: list[GoalProgress] = []
    for goal in plan.goals:
        cap = verified.get(goal.skill_id)
        level = cap.verified_level if cap else None
        done = [a for a in goal.actions if a.status == "done" or (a.catalogue_item_id in completed)]
        started = bool(done) or any(
            a.status == "in_progress" or a.catalogue_item_id in in_progress for a in goal.actions
        )
        total = len(goal.actions)
        pct = (
            100
            if level is not None and level >= goal.to_level
            else round(100 * len(done) / total)
            if total
            else 0
        )
        due = _when(goal.due_date)
        window = (due - created).total_seconds() if due else 0
        expected = (
            0 if window <= 0 else max(0, min(100, round(100 * (now - created).total_seconds() / window)))
        )
        overdue_actions = [
            a.title for a in goal.actions if a not in done and (d := _when(a.due_date)) and d < now
        ]
        status: GoalStatus
        if level is not None and level >= goal.to_level:
            status = "achieved"
        elif due is not None and due < now:
            status = "overdue"
        elif not started:
            status = "not_started"
        elif overdue_actions or pct + 25 < expected:
            status = "at_risk"
        else:
            status = "on_track"
        goals.append(
            GoalProgress(
                goal_id=goal.id,
                skill_id=goal.skill_id,
                skill_name=names.get(goal.skill_id, goal.skill_id),
                from_level=goal.from_level,
                to_level=goal.to_level,
                current_verified_level=level,
                status=status,
                progress_pct=pct,
                expected_pct=expected,
                actions_done=len(done),
                actions_total=total,
                overdue_actions=overdue_actions,
                completed_learning=[a.title for a in goal.actions if a.catalogue_item_id in completed],
            )
        )
    evidence: list[EvidenceItem] = []
    for cap in context.capabilities or []:
        verified_at = _when(cap.verified_at)
        if verified_at is not None and verified_at > created and cap.verified_level is not None:
            evidence.append(
                EvidenceItem(
                    source="verified_levels",
                    skill_id=cap.skill_id,
                    detail=f"Verified at level {cap.verified_level} since the plan started.",
                )
            )
    for record in context.learning_history or []:
        completed_at = _when(record.completed_at)
        if record.status == "completed" and completed_at is not None and completed_at > created:
            evidence.append(
                EvidenceItem(
                    source="learning_history",
                    skill_id=record.skill_ids[0] if record.skill_ids else None,
                    detail=f"Completed {record.title}.",
                )
            )
    evidence.extend(extra_evidence or [])
    overall = round(sum(g.progress_pct for g in goals) / len(goals)) if goals else 0
    return PlanProgressReport(
        plan_id=plan.id,
        employee_id=plan.employee_id,
        generated_at=now,
        overall_progress_pct=overall,
        goals=goals,
        new_evidence=evidence,
        unavailable_context=list(context.gaps_in_context),
    )


def to_plan_goal(goal: IdpGoal) -> PlanGoal:
    return PlanGoal(
        goal_key=goal.goal_key,
        skill_id=goal.skill_id,
        skill_name=goal.skill_name,
        from_level=goal.current_level or 0,
        to_level=goal.target_level,
        priority=goal.priority,
        objective=goal.objective,
        actions=goal.interventions,
        evidence_expectations=[*goal.expected_outcomes, *(m.measure for m in goal.milestones)],
    )


class ReviewPlanCapability(Capability[BaseModel, BaseModel]):
    spec = SPEC
    output_model = PlanReviewResult
    context_slices = frozenset(
        {"subject_profile", "role_profile", "framework", "capabilities", "learning_history"}
    )
    required_slices = frozenset({"capabilities"})

    async def run_step(
        self, ctx: RunContext, step: StepInput, context: CapabilityContext | None
    ) -> StepOutput:
        if self.deps.drafts is None or context is None or step.subject_employee_id is None:
            raise AppError("ai_unavailable", internal_detail="review prerequisites missing")
        plan_id = step.args.get("plan_id")
        trigger = step.args.get("trigger", "manual")
        if not plan_id:
            raise AppError("invalid_request", "plan_id is required.")
        if trigger not in TRIGGERS:
            raise AppError("invalid_request", f"trigger must be one of {sorted(TRIGGERS)}.")
        try:
            plan = await self.deps.backend.get_development_plan(ctx.principal, plan_id)
        except BackendError as exc:
            raise exc.to_app_error() from exc
        if plan.employee_id != step.subject_employee_id:
            raise AppError("invalid_request", "The plan does not belong to this employee.")
        payload = step.handoff_payload or {}
        scores = {k: int(v) for k, v in (payload.get("confirmed_scores") or {}).items()}
        coaching = planning.coaching_evidence(self.deps, ctx.principal.tenant_id, plan.employee_id)
        extra = [
            EvidenceItem(source="assessment", skill_id=k, detail=f"Reviewer-confirmed assessment score {v}.")
            for k, v in scores.items()
        ]
        extra += [
            EvidenceItem(source="coaching_practice", skill_id=c.get("skill_id"), detail=c["detail"])
            for c in coaching
        ]
        progress = compute_progress(plan, context, extra_evidence=extra)
        if step.args.get("progress_only") == "true":
            done = sum(g.status == "achieved" for g in progress.goals)
            return self._output(
                progress, None, f"Plan {progress.overall_progress_pct}% complete; {done} goal(s) achieved."
            )
        changes, new_goals_vctx, model = await self._changes(ctx, plan, progress, context, scores)
        if not changes:
            return self._output(progress, None, "The plan is on track; no changes are proposed.")
        adjustment = PlanAdjustmentPayload(
            plan_id=plan.id,
            trigger=trigger,
            changes=changes,
            rationale="; ".join(dict.fromkeys(c.reason for c in changes)),
            validation=DraftValidationReport(passed=True, repaired=False, issues=[]),
        )
        envelope = self.deps.drafts.create(
            ctx.principal,
            kind="plan_adjustment",
            capability=SPEC.capability,
            subject_employee_id=plan.employee_id,
            payload=adjustment,
            provenance=provenance(
                SPEC.capability, model=model, prompt_version=planning.PROMPT_VERSION, context=context
            ),
            approval_policy=approval_policy(self.deps.dev_plan_approval_mode).model_copy(
                update={"commit_endpoint_id": "BE-053"}
            ),
            disclaimer=DISCLAIMER,
            validation_context={
                "plan_id": plan.id,
                "goal_ids": [g.id for g in plan.goals],
                "action_ids": {g.id: [a.id for a in g.actions] for g in plan.goals},
                "new_goals": new_goals_vctx,
            },
        )
        return self._output(progress, envelope, f"{len(changes)} change(s) proposed for review.")

    @staticmethod
    def _output(progress: PlanProgressReport, envelope: Any, summary: str) -> StepOutput:
        result = PlanReviewResult(progress=progress, adjustment=envelope, summary=summary)
        return StepOutput(
            summary=summary, output_type="PlanReviewResult", data=result.model_dump(mode="json")
        )

    async def _changes(
        self,
        ctx: RunContext,
        plan: DevelopmentPlanDTO,
        progress: PlanProgressReport,
        context: CapabilityContext,
        scores: dict[str, int],
    ) -> tuple[list[PlanChange], dict[str, Any] | None, str]:
        changes: list[PlanChange] = []
        by_goal = {g.id: g for g in plan.goals}
        skills = [g.skill_id for g in plan.goals]
        active: set[str] | None
        try:
            items = await self.deps.backend.list_catalogue(ctx.principal, skills)
            active = {c.id for c in items if c.status == "active"}
        except BackendError:
            active = None  # catalogue unavailable: do not propose removals
        scenarios = self.deps.scenarios.list(ctx.principal.tenant_id) if self.deps.scenarios else []
        for gp in progress.goals:
            goal = by_goal[gp.goal_id]
            if gp.status == "achieved":
                changes.append(
                    PlanChange(
                        op="mark_goal_complete",
                        goal_ref=goal.id,
                        action_ref=None,
                        goal=None,
                        action=None,
                        reason=f"{gp.skill_name} verified at the target level.",
                    )
                )
                continue
            for action in goal.actions:
                if (
                    active is not None
                    and action.catalogue_item_id
                    and action.catalogue_item_id not in active
                    and action.status != "done"
                ):
                    changes.append(
                        PlanChange(
                            op="remove_action",
                            goal_ref=goal.id,
                            action_ref=action.id,
                            goal=None,
                            action=None,
                            reason=f"'{action.title}' is no longer in the catalogue.",
                        )
                    )
            if gp.status in ("at_risk", "overdue") and not any(a.scenario_id for a in goal.actions):
                scenario = next(
                    (s for s in scenarios if goal.skill_id in {t.skill_id for t in s.target_skills}), None
                )
                if scenario is not None:
                    changes.append(
                        PlanChange(
                            op="add_action",
                            goal_ref=goal.id,
                            action_ref=None,
                            goal=None,
                            action=PlanAction(
                                action_key=f"practice-{goal.id}",
                                type="coaching_scenario",
                                title=f"Practise: {scenario.title}",
                                description="Rehearse the skill in an AI role-play and review the feedback.",
                                catalogue_item_id=None,
                                scenario_id=scenario.scenario_id,
                                success_indicator_ids=[],
                                due_in_days=14,
                            ),
                            reason=f"{gp.skill_name} is {gp.status.replace('_', ' ')}; add practice.",
                        )
                    )
        covered = set(skills)
        new_skills = sorted(
            ({g.skill_id for g in context.skill_gaps if g.priority in ("critical", "high")} | set(scores))
            - covered
        )
        if not new_skills:
            return changes, None, "none"
        goals = planning.select_goals(
            context, focus_skill_ids=[], assessment_scores=scores, max_goals=self.deps.dev_plan_max_goals
        )
        goals = [g for g in goals if g.skill_id in new_skills]
        if not goals:
            return changes, None, "none"
        evidence, completed = planning.evidence_from(context, scores, [])
        inputs = planning.PlanningInputs(
            context=context,
            goals=goals,
            horizon_weeks=12,
            hours_per_week=None,
            evidence=evidence,
            completed_items=completed,
        )
        await planning.gather_candidates(self.deps, ctx, inputs)
        assert context.role_profile is not None
        employee = EmployeeRef(
            employee_id=plan.employee_id,
            job_title=None,
            department=None,
            current_role_id=context.role_profile.role_id,
            plan_role_id=context.role_profile.role_id,
            plan_role_title=context.role_profile.title,
            role_profile_version=context.role_profile.version,
        )
        generated, model = await planning.generate_plan(self.deps, ctx, inputs, employee)
        for new_goal in generated.goals:
            changes.append(
                PlanChange(
                    op="add_goal",
                    goal_ref=new_goal.goal_key,
                    action_ref=None,
                    goal=to_plan_goal(new_goal),
                    action=None,
                    reason=f"New evidence shows a {new_goal.priority} gap in {new_goal.skill_name}.",
                )
            )
        return changes, planning.validation_context(inputs), model


