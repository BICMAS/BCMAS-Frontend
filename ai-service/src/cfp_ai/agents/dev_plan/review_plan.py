"""D4 ``dev_plan.review_plan`` — progress tracking and evidence-driven plan updates.

Progress is computed deterministically from the official plan (BE-051), verified levels
(BE-030) and learning records (BE-042). Updates are proposed — never applied — as a
``plan_adjustment`` draft that needs the same review as a new plan:

  * goal achieved (verified level ≥ target)        → mark_goal_complete
  * learning item no longer in the active catalogue → remove_action
  * goal at risk / overdue, practice scenario exists → add_action (coaching scenario)
  * new gap evidence not covered by the plan          → add_goal (generated by the planner)
    (sources: new critical/high gaps, reviewer-confirmed assessment scores via handoff)
"""

